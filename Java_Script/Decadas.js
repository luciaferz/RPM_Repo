function getCurrentDecade() {
  const params = new URLSearchParams(window.location.search);
  const requested = params.get("decada");
  if (requested && DECADES_DATA[requested]) {
    return requested;
  }
  return "1960";
}

function applyDecadeTheme(decadeKey) {
  const theme = DECADE_THEME[decadeKey] || DECADE_THEME["1960"];
  const root = document.documentElement;

  root.style.setProperty("--decade-accent", theme.accent);
  root.style.setProperty("--decade-accent-soft", theme.accentSoft);
  root.style.setProperty("--decade-accent-glow", theme.accentGlow);
  root.style.setProperty("--decade-accent-light", theme.accentLight);
  root.style.setProperty("--decade-tint", theme.tint || "rgba(230, 57, 70, 0.12)");
}

