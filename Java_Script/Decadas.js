function renderDecade(decadeKey) {
  const decade = DECADES_DATA[decadeKey];
  const heading = document.getElementById("decadeHeading");
  const lead = document.getElementById("garageLead");
  const narrative = document.getElementById("decadeNarrative");
  const subheading = document.getElementById("decadeSubheading");
  const content = document.getElementById("decadeContent");
  const grid = document.getElementById("carsGrid");

  if (!decade || !heading || !lead || !grid) return;

  document.body.setAttribute("data-decade", decadeKey);
  applyDecadeTheme(decadeKey);

  heading.className = DECADE_TITLE_CLASS[decadeKey] || "Titulo_Seccion60s";
  heading.textContent = decade.title;

  lead.textContent = decade.lead;

  if (narrative) {
    narrative.textContent = decade.narrative || "Selección de modelos con relevancia histórica y emocional.";
  }

  if (subheading) {
    subheading.textContent = `Piezas clave de ${decade.title.slice(0, 4)}`;
  }

  if (content) {
    content.setAttribute("data-decade", decadeKey);
  }

  grid.innerHTML = decade.cars.map((car) => buildCard(car)).join("");
}

function setActiveDecadeStyles(decadeKey) {
  document.querySelectorAll("[data-pill]").forEach((pill) => {
    pill.classList.toggle("is-active", pill.dataset.pill === decadeKey);
  });

  document.querySelectorAll(".decade-filter-link").forEach((link) => {
    link.classList.toggle("active", link.dataset.decadeLink === decadeKey);
  });
}

function scrollToHashAfterRender() {
  if (!window.location.hash) return;
  const target = document.querySelector(window.location.hash);
  if (!target) return;

  setTimeout(() => {
    target.scrollIntoView({ behavior: "smooth", block: "start" });
  }, 120);
}

function normalizeIndex(index, total) {
  if (!total) return 0;
  return (index + total) % total;
}

function updateGalleryImages(card, car, nextIndex) {
  const total = car.images.length;
  if (!total) return;

  const currentIndex = normalizeIndex(nextIndex, total);
  const leftIndex = normalizeIndex(currentIndex - 1, total);
  const rightIndex = normalizeIndex(currentIndex + 1, total);

  const mainImage = card.querySelector(".car-image");
  const leftImage = card.querySelector(".side-left img");
  const rightImage = card.querySelector(".side-right img");

  const current = car.images[currentIndex];
  const left = car.images[leftIndex];
  const right = car.images[rightIndex];

  if (mainImage && current) {
    mainImage.src = current.src;
    mainImage.alt = current.alt;
  }

  if (leftImage && left) {
    leftImage.src = left.src;
    leftImage.alt = left.alt;
  }

  if (rightImage && right) {
    rightImage.src = right.src;
    rightImage.alt = right.alt;
  }

  card.dataset.currentIndex = String(currentIndex);
}

function setupInteractiveGalleries() {
  document.querySelectorAll(".car-card").forEach((card) => {
    const carId = card.dataset.carId;
    const decadeKey = getCurrentDecade();
    const car = DECADES_DATA[decadeKey]?.cars.find((item) => item.id === carId);
    const mainButton = card.querySelector(".gallery-main");
    if (!mainButton || !car || !car.images?.length) return;

    updateGalleryImages(card, car, Number(card.dataset.currentIndex || 0));

    const nextSlide = () => {
      const currentIndex = Number(card.dataset.currentIndex || 0);
      updateGalleryImages(card, car, currentIndex + 1);
    };

    const startAuto = () => {
      if (car.images.length < 2 || galleryTimers.has(card)) return;
      const timer = setInterval(nextSlide, 4200);
      galleryTimers.set(card, timer);
    };

    const stopAuto = () => {
      const timer = galleryTimers.get(card);
      if (!timer) return;
      clearInterval(timer);
      galleryTimers.delete(card);
    };

    mainButton.addEventListener("click", () => {
      card.classList.add("is-expanded");
      nextSlide();
    });

    card.addEventListener("mouseenter", () => {
      card.classList.add("is-expanded");
      startAuto();
    });

    card.addEventListener("mouseleave", () => {
      card.classList.remove("is-expanded");
      stopAuto();
    });

    mainButton.addEventListener("blur", () => {
      if (!card.matches(":hover")) {
        card.classList.remove("is-expanded");
        stopAuto();
      }
    });
  });
}

function setupCardTabs() {
  document.querySelectorAll(".car-card").forEach((card) => {
    const tabButtons = Array.from(card.querySelectorAll("[data-tab-btn]"));
    const tabPanels = Array.from(card.querySelectorAll("[data-tab-panel]"));
    if (!tabButtons.length || !tabPanels.length) return;

    tabButtons.forEach((button) => {
      button.addEventListener("click", () => {
        const target = button.dataset.tabBtn;
        tabButtons.forEach((item) => item.classList.toggle("is-active", item === button));
        tabPanels.forEach((panel) => panel.classList.toggle("is-active", panel.dataset.tabPanel === target));
      });
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const currentDecade = getCurrentDecade();
  renderDecade(currentDecade);
  setupCardTabs();
  setActiveDecadeStyles(currentDecade);
  setupInteractiveGalleries();
  scrollToHashAfterRender();
});
